  )''',
  'ALTER TABLE products ENABLE ROW LEVEL SECURITY',
  'CREATE POLICY products_own ON products FOR ALL TO authenticated USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid())',
  // Events: many rows, for bulk writes and batches.
