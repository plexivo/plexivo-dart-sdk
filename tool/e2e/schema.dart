  'ALTER TABLE comments ENABLE ROW LEVEL SECURITY',
  'CREATE POLICY comments_read ON comments FOR SELECT TO anon, authenticated USING (EXISTS (SELECT 1 FROM posts p WHERE p.id = post_id))',
