    published_on date,
    published_at timestamptz,
    external_id uuid NOT NULL DEFAULT gen_random_uuid(),
    search tsvector GENERATED ALWAYS AS (to_tsvector('english', title || ' ' || body)) STORED,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT posts_author_fk FOREIGN KEY (author_id) REFERENCES profiles (id) ON DELETE CASCADE,
    CONSTRAINT posts_editor_fk FOREIGN KEY (editor_id) REFERENCES profiles (id) ON DELETE SET NULL
