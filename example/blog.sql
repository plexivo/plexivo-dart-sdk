-- The blog the README's examples use: profiles, posts, comments, tags,
-- a shop's products, a view with joins and a few functions. Run it once as
-- the database owner (psql through `plexivo db connect`, or with the secret
-- key: `server.sql.transaction(statements)` from a server).
--
-- Every table has row-level security on and policies; that is the whole
-- security model. The publishable key in an app can do nothing they don't
-- allow.

CREATE TYPE post_status AS ENUM ('draft', 'published', 'archived');

CREATE TABLE profiles (
  id uuid PRIMARY KEY DEFAULT auth.uid(),
  username text NOT NULL UNIQUE,
  country text,
  avatar_url text
);
ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;
CREATE POLICY profiles_read ON profiles FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY profiles_write ON profiles FOR ALL TO authenticated USING (id = auth.uid()) WITH CHECK (id = auth.uid());

CREATE TABLE posts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author_id uuid NOT NULL DEFAULT auth.uid() REFERENCES profiles (id) ON DELETE CASCADE,
  title text NOT NULL CHECK (length(title) BETWEEN 1 AND 200),
  body text NOT NULL DEFAULT '',
  status post_status NOT NULL DEFAULT 'draft',
  likes integer NOT NULL DEFAULT 0,
  tags text[] NOT NULL DEFAULT '{}',
  meta jsonb NOT NULL DEFAULT '{}',
  search tsvector GENERATED ALWAYS AS (to_tsvector('english', title || ' ' || body)) STORED,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE posts ENABLE ROW LEVEL SECURITY;
-- Published posts are public; drafts are their author's alone.
CREATE POLICY posts_read ON posts FOR SELECT TO anon, authenticated USING (status = 'published' OR author_id = auth.uid());
CREATE POLICY posts_write ON posts FOR ALL TO authenticated USING (author_id = auth.uid()) WITH CHECK (author_id = auth.uid());

CREATE TABLE comments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id bigint NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
  author_id uuid NOT NULL DEFAULT auth.uid() REFERENCES profiles (id) ON DELETE CASCADE,
  body text NOT NULL,
  approved boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE comments ENABLE ROW LEVEL SECURITY;
CREATE POLICY comments_read ON comments FOR SELECT TO anon, authenticated USING (EXISTS (SELECT 1 FROM posts p WHERE p.id = post_id));
CREATE POLICY comments_write ON comments FOR INSERT TO authenticated WITH CHECK (author_id = auth.uid());

CREATE TABLE tags (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE
);
ALTER TABLE tags ENABLE ROW LEVEL SECURITY;
CREATE POLICY tags_read ON tags FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY tags_add ON tags FOR INSERT TO authenticated WITH CHECK (true);

CREATE TABLE post_tags (
  post_id bigint NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
  tag_id bigint NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
  PRIMARY KEY (post_id, tag_id)
);
ALTER TABLE post_tags ENABLE ROW LEVEL SECURITY;
CREATE POLICY post_tags_read ON post_tags FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY post_tags_write ON post_tags FOR ALL TO authenticated
  USING (EXISTS (SELECT 1 FROM posts p WHERE p.id = post_id AND p.author_id = auth.uid()))
  WITH CHECK (EXISTS (SELECT 1 FROM posts p WHERE p.id = post_id AND p.author_id = auth.uid()));

CREATE TABLE products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id uuid NOT NULL DEFAULT auth.uid(),
  sku text NOT NULL,
  region text NOT NULL,
  name text NOT NULL,
  price numeric(12,2) NOT NULL DEFAULT 0,
  stock integer NOT NULL DEFAULT 0,
  UNIQUE (owner_id, sku, region)
);
ALTER TABLE products ENABLE ROW LEVEL SECURITY;
CREATE POLICY products_own ON products FOR ALL TO authenticated USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid());

-- A view with joins: with security_invoker it runs with the caller's rights,
-- so every table's policies still apply.
CREATE VIEW post_feed WITH (security_invoker = true) AS
  SELECT p.id, p.title, p.likes, p.created_at, pr.username AS author,
         (SELECT count(*) FROM comments c WHERE c.post_id = p.id) AS comments
  FROM posts p JOIN profiles pr ON pr.id = p.author_id;

-- Functions apps may call: COMMENT … '@expose' opts each one in.
CREATE FUNCTION search_posts(q text) RETURNS SETOF posts LANGUAGE sql STABLE AS
  $$ SELECT * FROM posts WHERE search @@ websearch_to_tsquery('english', q) $$;
COMMENT ON FUNCTION search_posts(text) IS 'Full-text search over posts. @expose';

CREATE FUNCTION posts_per_author() RETURNS TABLE (author text, posts bigint, likes bigint) LANGUAGE sql STABLE AS
  $$ SELECT pr.username, count(*), sum(p.likes)::bigint FROM posts p JOIN profiles pr ON pr.id = p.author_id GROUP BY pr.username $$;
COMMENT ON FUNCTION posts_per_author() IS '@expose';

CREATE FUNCTION like_post(post bigint) RETURNS integer LANGUAGE sql SECURITY DEFINER SET search_path = public AS
  $$ UPDATE posts SET likes = likes + 1 WHERE id = post AND status = 'published' RETURNING likes $$;
COMMENT ON FUNCTION like_post(bigint) IS 'Anyone may like a published post. @expose';

GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT SELECT ON ALL TABLES IN SCHEMA public TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON profiles, posts, comments, tags, post_tags, products TO authenticated;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO authenticated;

-- Realtime for posts and comments: each change is announced, and every
-- subscriber receives it only if their policies let them read the row.
CREATE TRIGGER plexivo_realtime AFTER INSERT OR UPDATE OR DELETE ON posts
  FOR EACH ROW EXECUTE FUNCTION auth.realtime_notify('id');
CREATE TRIGGER plexivo_realtime AFTER INSERT OR UPDATE OR DELETE ON comments
  FOR EACH ROW EXECUTE FUNCTION auth.realtime_notify('id');
