-- The tables every example uses. Run it once, as the database owner:
--   PLEXIVO_URL=… PLEXIVO_SECRET_KEY=… dart run example/setup.dart   (secret key, from your machine)
-- or paste it into psql through `plexivo db connect YOUR_DATABASE`.
--
-- A table appears in the Data API only with row-level security on and at
-- least one policy. The policies below are the whole security model:
-- the publishable key in your app can do nothing they don't allow.

-- Todos: each signed-in user sees and changes only their own.
CREATE TABLE IF NOT EXISTS public.todos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id uuid NOT NULL DEFAULT auth.uid(),
  title text NOT NULL CHECK (length(title) BETWEEN 1 AND 200),
  done boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.todos ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS own_todos ON public.todos;
CREATE POLICY own_todos ON public.todos FOR ALL TO authenticated
  USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid());
GRANT USAGE ON SCHEMA public TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.todos TO authenticated;

-- Messages: one chat for everyone signed in; you post only as yourself.
CREATE TABLE IF NOT EXISTS public.messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author_id uuid NOT NULL DEFAULT auth.uid(),
  room text NOT NULL DEFAULT 'lobby',
  body text NOT NULL CHECK (length(body) BETWEEN 1 AND 2000),
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS read_messages ON public.messages;
CREATE POLICY read_messages ON public.messages FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS post_as_yourself ON public.messages;
CREATE POLICY post_as_yourself ON public.messages FOR INSERT TO authenticated
  WITH CHECK (author_id = auth.uid());
GRANT SELECT, INSERT ON public.messages TO authenticated;

-- Then, in the console, open the database's Realtime tab (or Data API →
-- the table → Realtime) and switch Realtime on for todos and messages.
